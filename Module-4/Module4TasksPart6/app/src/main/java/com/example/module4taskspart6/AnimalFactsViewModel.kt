package com.example.module4taskspart6

import androidx.lifecycle.ViewModel
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.flow

/**
 * Задание 12: ViewModel для генератора фактов о животных.
 * Использует cold Flow — каждый новый collect запускает генерацию заново.
 */
class AnimalFactsViewModel : ViewModel() {

    // Список фактов о животных
    private val animalFacts = listOf(
        "🐘 Слоны — единственные животные, которые не умеют прыгать.",
        "🦈 Акулы старше деревьев: они существуют около 450 млн лет.",
        "🐙 У осьминога три сердца и голубая кровь.",
        "🦁 Лев спит до 20 часов в сутки.",
        "🐬 Дельфины спят с одним открытым глазом.",
        "🦋 Бабочки ощущают вкус лапками.",
        "🐧 Пингвины — единственные птицы, которые умеют плавать, но не летают.",
        "🦒 У жирафа такое же количество шейных позвонков, как у человека — 7.",
        "🐝 Пчела машет крыльями около 200 раз в секунду.",
        "🦅 Орлы могут видеть добычу с расстояния 3 километра.",
        "🐠 Рыбы-клоуны все рождаются самцами и могут сменить пол.",
        "🐌 Улитка может спать до 3 лет подряд.",
        "🦜 Попугаи ара живут до 80 лет и дольше.",
        "🐻 Медведи бегут со скоростью до 60 км/ч — быстрее лошади.",
        "🦩 Фламинго розовые из-за пигментов в пище — без неё они были бы белыми.",
        "🐊 Крокодилы не умеют высовывать язык.",
        "🦊 Лисы используют магнитное поле Земли для охоты.",
        "🐋 Сердце синего кита весит около 600 кг — размером с автомобиль.",
        "🐜 Муравьи могут поднимать груз в 50 раз тяжелее себя.",
        "🦔 Ёжики иммунны к яду большинства змей."
    )

    /**
     * Возвращает cold Flow, который при каждом collect:
     * 1. Начинает генерацию заново (с задержкой для имитации загрузки)
     * 2. Выдаёт один случайный факт через emit()
     *
     * Cold Flow — правильный выбор здесь, потому что каждое нажатие
     * кнопки должно запускать новый независимый запрос.
     */
    fun getRandomFact(): Flow<String> = flow {
        // Имитируем задержку загрузки от 1500 до 2500 мс
        delay((1500L..2500L).random())
        // Выдаём случайный факт
        emit(animalFacts.random())
    }
}